# PlatformIO post-script: keeps the firmware inside its 1 MB OTA slot.
#
# 1. printf family from the chip ROM. The Arduino core links newlib's full
#    printf four times over (vfprintf, svfprintf and their integer twins,
#    ~50 KB). ESP-IDF's CONFIG_NEWLIB_NANO_FORMAT instead takes printf/vfprintf
#    from the ESP32-S3 ROM and sprintf/snprintf from libc_nano; this does the
#    same. Cost: no %f and no %ll in printf formats (use %lu / String()).
# 2. No ESP Insights log hooks. The core wraps esp_log_write / log_printf so
#    ESP Insights can see logs, which links esp_diagnostics. Nothing uses it.
# 3. The web pages (web/*.html, web/*.css) are gzipped into a generated
#    header, web_pages.h, served with Content-Encoding: gzip.
#
# The other size settings are build flags in platformio.ini (no C++ unwind
# tables, NimBLE roles and pairing) and src/no_coredump.c.
Import("env", "projenv")
import gzip, os

env.Append(LINKFLAGS=["--specs=nano.specs", "-Wl,-T,esp32s3.rom.newlib-nano.ld"])
for flag in ("-Wl,--wrap=esp_log_write", "-Wl,--wrap=esp_log_writev", "-Wl,--wrap=log_printf"):
    while flag in env["LINKFLAGS"]:
        env["LINKFLAGS"].remove(flag)

PAGES = [("faces.html", "FACES_HTML"), ("settings.html", "SETTINGS_HTML"), ("style.css", "STYLE_CSS")]


def gen_pages():
    web = os.path.join(env.subst("$PROJECT_DIR"), "web")
    out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
    out = ["/* Generated by slim.py from web/ -- edit those files, not this one. */",
           "#pragma once", "#include <pgmspace.h>", "#include <stddef.h>", "#include <stdint.h>", ""]
    for fname, sym in PAGES:
        raw = open(os.path.join(web, fname), "rb").read()
        gz = gzip.compress(raw, 9, mtime=0)
        body = ",".join(str(b) for b in gz)
        out.append(f"// {fname}: {len(raw)} bytes, {len(gz)} gzipped")
        out.append(f"static const uint8_t {sym}_GZ[] PROGMEM = {{{body}}};")
        out.append(f"static const size_t {sym}_GZ_LEN = {len(gz)};")
        out.append("")
    text = "\n".join(out)
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "web_pages.h")
    if not os.path.exists(path) or open(path).read() != text:   # unchanged: keep the mtime, no rebuild
        open(path, "w").write(text)
    projenv.Append(CPPPATH=[out_dir])


gen_pages()
