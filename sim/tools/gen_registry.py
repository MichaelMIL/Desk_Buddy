#!/usr/bin/env python3
"""
gen_registry.py - regenerate hardware/src/animations/animations.h from the
anim_*.h files in that directory (one entry per exported animation).

  python3 sim/tools/gen_registry.py hardware/src/animations
"""
import os
import re
import sys

SYM_RE = re.compile(r"const\s+uint8_t\s+(anim_[A-Za-z0-9_]+)\s*\[\]")


def generate(anim_dir):
    entries = []
    for fn in sorted(os.listdir(anim_dir)):
        if not (fn.startswith("anim_") and fn.endswith(".h")):
            continue
        with open(os.path.join(anim_dir, fn), encoding="utf-8") as fh:
            m = SYM_RE.search(fh.read())
        if m:
            entries.append((fn, m.group(1)))
    lines = [
        "/* Generated by sim/tools/gen_registry.py - do not edit, re-run instead. */",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
    ]
    lines += ['#include "%s"' % fn for fn, _ in entries]
    lines += [
        "",
        "typedef struct { const char *name; const uint8_t *data; size_t len; } anim_entry_t;",
        "",
        "static const anim_entry_t ANIMATIONS[] = {",
    ]
    lines += ['  { "%s", %s, %s_len },' % (sym[5:], sym, sym) for _, sym in entries]
    if not entries:
        lines.append("  { \"none\", (const uint8_t *)0, 0 },")
    lines += [
        "};",
        "static const size_t ANIMATIONS_COUNT = %d;" % len(entries),
        "",
    ]
    with open(os.path.join(anim_dir, "animations.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return [sym for _, sym in entries]


if __name__ == "__main__":
    d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "hardware", "src", "animations")
    syms = generate(d)
    print("animations.h: %d animation(s)%s" % (len(syms), (": " + ", ".join(syms)) if syms else ""))
